#!/usr/bin/env node
// Writes assets/licenses/mermaid-bundle.txt: the licence text of each package that the pinned build
// mermaid/dist/mermaid.min.js bundles. The script walks the runtime dependencies of the installed mermaid package.
// Run it again after a change of the pinned Mermaid version.

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const TARGET = path.join(root, "assets", "licenses", "mermaid-bundle.txt");
const LICENCE_FILE = /^(licen[sc]e|copying)/i;

function resolvePackage(name, from) {
  for (let dir = from; ; dir = path.dirname(dir)) {
    const file = path.join(dir, "node_modules", name, "package.json");
    if (existsSync(file)) return file;
    if (path.dirname(dir) === dir) throw new Error(`cannot resolve ${name} from ${from}`);
  }
}

const seen = new Map();
function walk(name, from) {
  const file = resolvePackage(name, from);
  const pkg = JSON.parse(readFileSync(file, "utf8"));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) return;
  const dir = path.dirname(file);
  const licence = readdirSync(dir).find((f) => LICENCE_FILE.test(f));
  const text = licence === undefined ? `The package ships no licence file. Its package.json names the licence ${pkg.license}.` : readFileSync(path.join(dir, licence), "utf8").trim();
  seen.set(key, { licence: pkg.license ?? "see the text", text });
  for (const dep of Object.keys(pkg.dependencies ?? {})) {
    if (!dep.startsWith("@types/")) walk(dep, dir);
  }
}

walk("mermaid", root);
const parts = [...seen].sort(([a], [b]) => a.localeCompare(b)).map(([key, v]) => `==== ${key} (${v.licence}) ====\n\n${v.text}\n`);
const header = "Licence texts of the packages that the pinned build mermaid.min.js bundles.\nGenerated by scripts/mermaid-licenses.mjs from the installed mermaid package. Do not edit this file by hand.\n\n";
writeFileSync(TARGET, header + parts.join("\n").replace(/\r\n/g, "\n"));
process.stdout.write(`wrote ${seen.size} packages to ${path.relative(root, TARGET)}\n`);
